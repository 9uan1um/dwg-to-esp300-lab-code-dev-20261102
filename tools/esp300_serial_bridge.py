"""Loopback-only RFC2217 bridge for WSL's PL2303 serial device.

Run in Linux: python3 tools/esp300_serial_bridge.py --device /dev/ttyUSB0
Windows connects to rfc2217://127.0.0.1:22170 using WSL localhost forwarding.
No ESP300 commands are generated by the bridge. Only one client is served.
"""
from __future__ import annotations

import argparse
import logging
import socket
import threading
import time

import serial
from serial.rfc2217 import PortManager

LOG = logging.getLogger("esp300.bridge")
PROTOCOL_LOG = logging.getLogger("esp300.bridge.protocol")
# Purges occur before every position query. Logging every RFC2217 packet
# can block an unattended console/pipe and should be an opt-in diagnostic.
PROTOCOL_LOG.setLevel(logging.WARNING)


class SocketWriter:
    def __init__(self, sock):
        self.sock = sock
        self.lock = threading.Lock()

    def write(self, data):
        with self.lock:
            self.sock.sendall(data)


def serve_client(client, device, baudrate=19200):
    """Close the serial handle and TCP connection on either side's failure."""
    stopped = threading.Event()
    client.settimeout(2)
    client.setsockopt(socket.IPPROTO_TCP, socket.TCP_NODELAY, 1)
    with client, serial.serial_for_url(
        device, baudrate=baudrate, timeout=0.02, write_timeout=2, rtscts=True,
    ) as port:
        writer = SocketWriter(client)
        manager = PortManager(port, writer, logger=PROTOCOL_LOG)
        # PortManager.filter handles PURGE_DATA and serial reconfiguration.
        # Neither may race a POSIX read between select() and os.read(): a
        # concurrent input purge can otherwise look like a USB disconnection.
        serial_lock = threading.Lock()

        def serial_to_client():
            try:
                next_modem_check = 0.0
                while not stopped.is_set():
                    with serial_lock:
                        data = port.read(port.in_waiting or 1)
                        if time.monotonic() >= next_modem_check:
                            manager.check_modem_lines()
                            next_modem_check = time.monotonic() + 0.5
                    if data:
                        writer.write(b"".join(manager.escape(data)))
                    # Give a waiting client operation the lock after a timed
                    # read; do not continuously reacquire and starve purges.
                    stopped.wait(0.001)
            except (OSError, serial.SerialException) as error:
                LOG.warning("Serial/USB link ended: %s", error)
                stopped.set()
                try:
                    client.shutdown(socket.SHUT_RDWR)
                except OSError:
                    pass

        reader = threading.Thread(target=serial_to_client, daemon=True)
        reader.start()
        try:
            while not stopped.is_set():
                try:
                    data = client.recv(4096)
                except socket.timeout:
                    continue
                if not data:
                    break
                with serial_lock:
                    payload = b"".join(manager.filter(data))
                    if payload:
                        port.write(payload)
        finally:
            stopped.set()
            reader.join(timeout=3)
            # Closing the serial port drops its line state, not ESP motor power.


def run_server(device, port=22170, baudrate=19200):
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as listener:
        listener.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        listener.bind(("127.0.0.1", port))
        listener.listen(1)
        LOG.info("Listening on 127.0.0.1:%s -> %s (one client at a time)", port, device)
        while True:
            client, address = listener.accept()
            LOG.info("Client %s", address)
            try:
                serve_client(client, device, baudrate)
            except (OSError, serial.SerialException) as error:
                client.close()
                LOG.error("Connection failed: %s", error)
            LOG.info("Client disconnected; ready for another connection")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--device", required=True)
    parser.add_argument("--port", type=int, default=22170)
    parser.add_argument("--baudrate", type=int, default=19200)
    parser.add_argument("--verbose", action="store_true", help="Log RFC2217 negotiation and purge packets for diagnosis only.")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    if args.verbose:
        PROTOCOL_LOG.setLevel(logging.INFO)
    try:
        run_server(args.device, args.port, args.baudrate)
    except KeyboardInterrupt:
        pass
